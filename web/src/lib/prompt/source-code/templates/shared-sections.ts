/**
 * 議会名のセクション。議会が分からないときは空文字を返す。
 */
export function buildAssemblySection(assemblyName: string): string {
  if (!assemblyName) return "";
  return `## いま見ている議会

ユーザーは「${assemblyName}」のページを見ています。とくに断りがなければ、質問は${assemblyName}の議案・会期についてのものとして答えてください。
`;
}

